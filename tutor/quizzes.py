def quiz_for_track(track):
    questions = TRACK_QUIZZES.get(track, [])
    result = []
    offset = sum(ord(character) for character in track) % 3
    for index, question in enumerate(questions):
        answer = (offset + index) % len(question["choices"])
        choices = question["choices"]
        rotated = choices[-answer:] + choices[:-answer] if answer else choices[:]
        result.append({**question, "choices": rotated, "answer": answer})
    return result
