def get_lesson(slug):
    return next((lesson for lesson in LESSONS if lesson["slug"] == slug), None)


def get_tracks(completed_slugs=()):
    completed = set(completed_slugs)
    tracks = []
    tracks_by_title = {}
    for lesson in LESSONS:
        track = tracks_by_title.get(lesson["track"])
        if track is None:
            track = {"title": lesson["track"], "lessons": []}
            tracks_by_title[lesson["track"]] = track
            tracks.append(track)
        track["lessons"].append(
            {
                **lesson,
                "language": lesson.get("language", "Python"),
                "completed": lesson["slug"] in completed,
            }
        )
    return tracks
